'use strict';
const assert=require('node:assert/strict'), I=require('../inventory-core.js');
const now='2026-11-03',stamp=now+'T12:00:00.000Z';
let d={lots:[{id:'LOT',bottles:960,unitCost:144}],moves:[],documents:[{keep:true}]};
d=I.saveOpening(d,'LOT',{asOf:now,rows:[{location:'Oaxaca',tag:'Nacional',amount:80,unit:'box'}],complete:true,stamp},now);
d=I.addLocation(d,'Distribuidor · Georgia',{kind:'distributor',address:'Bodega Georgia',contact:'Responsable'});
d=I.addLocation(d,'Cliente · Centro',{kind:'client',address:'CDMX'});
const input={id:'A',from:'Oaxaca',to:'Distribuidor · Georgia',tag:'Nacional',amount:10,unit:'box',date:now,purpose:'consignment',costKnown:true,costAmount:1500,currency:'MXN',stamp};
const original=JSON.stringify(d);
d=I.saveShipment(d,'LOT',input,now);
assert.equal(JSON.parse(original).lotShipments,undefined);
let b=I.balance(d,'LOT');assert.equal(b.total,420);assert.equal(b.transit,60);assert.equal(b.knownTotal,480);
assert.equal(d.lotShipments[0].inputAmount,10);assert.equal(d.lotShipments[0].inputUnit,'box');assert.equal(d.lotShipments[0].destination.kind,'distributor');assert.equal(d.lotShipments[0].destination.address,'Bodega Georgia');
d=I.receive(d,'LOT','A',now,now,stamp);b=I.balance(d,'LOT');assert.equal(b.total,480);assert.equal(b.transit,0);assert.equal(b.atThirdParties,60);assert.equal(b.deliveredSales,0);
assert.throws(()=>I.receive(d,'LOT','A',now,now,stamp));
assert.throws(()=>I.saveShipment(d,'LOT',{...input,id:'X',amount:71},now),/Solo hay 420/);
assert.throws(()=>I.saveShipment(d,'LOT',{...input,id:'X',purpose:'transfer'},now),/consignación/);
assert.throws(()=>I.saveShipment(d,'LOT',{...input,id:'X',purpose:'unknown'},now));
assert.throws(()=>I.saveShipment(d,'LOT',{...input,id:'X',amount:1.5},now));
assert.throws(()=>I.addLocation(d,'Oaxaca',{kind:'client'}));
assert.throws(()=>I.addLocation(d,'Otra',{kind:'bad'}));
d=I.saveShipment(d,'LOT',{...input,id:'B',to:'Cliente · Centro',amount:5,purpose:'sale'},now);
b=I.balance(d,'LOT');assert.equal(b.total,450);assert.equal(b.transit,30);assert.equal(b.knownTotal,480);
d=I.receive(d,'LOT','B',now,now,stamp);b=I.balance(d,'LOT');assert.equal(b.total,450);assert.equal(b.transit,0);assert.equal(b.deliveredSales,30);assert.equal(b.rows.find(r=>r.location==='Cliente · Centro'),undefined);
d=I.saveShipment(d,'LOT',{...input,id:'C',from:'Distribuidor · Georgia',to:'CDMX',amount:2,purpose:'transfer',received:true},now);
b=I.balance(d,'LOT');assert.equal(b.total,450);assert.equal(b.atThirdParties,48);assert.equal(b.rows.find(r=>r.location==='CDMX').quantity,12);
assert.equal(b.knownTotal+b.deliveredSales,480);
d=I.saveShipment(d,'LOT',{...input,id:'D',historical:true,date:'',amount:'',to:'Cliente · Centro',purpose:'sale'},now);
assert.equal(I.balance(d,'LOT').total,450);assert.equal(I.balance(d,'LOT').deliveredSales,30);
assert.equal(d.lots[0].unitCost,144);assert.deepEqual(d.documents,[{keep:true}]);
assert.equal(d.lotShipments[0].destination.address,'Bodega Georgia');
assert.equal(I.costTotals(d,'LOT').byCurrency.MXN,6000);
let old=JSON.parse(original);old=I.saveShipment(old,'LOT',{...input,id:'OLD',to:'CDMX',purpose:undefined,received:true},now);delete old.lotShipments[0].purpose;delete old.lotShipments[0].destination;
assert.equal(I.balance(old,'LOT').total,480);assert.equal(I.balance(old,'LOT').rows.find(r=>r.location==='CDMX').quantity,60);
console.log('PASS: destination types, boxes, transit, consignment, delivered sales, returns, historical data, cost preservation and overship prevention');
